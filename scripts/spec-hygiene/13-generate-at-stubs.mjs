#!/usr/bin/env node
/**
 * Auto-generate missing 97-acceptance-criteria.md rollup stubs.
 * Closes audit finding F-09. Idempotent — safe to re-run.
 *
 * Reads warnings from 08-check-acceptance-coverage.mjs (stderr), then writes
 * a standardized stub to each missing folder.
 */
import { execSync } from "node:child_process";
import { writeFileSync, existsSync, readdirSync } from "node:fs";
import { join, basename } from "node:path";

// 08-check-acceptance-coverage.mjs writes warnings to stderr; capture both streams.
const OUT = execSync(
  "node scripts/spec-hygiene/08-check-acceptance-coverage.mjs 2>&1 1>/dev/null",
  { encoding: "utf8", shell: "/bin/bash" }
);

const folders = [];
for (const line of OUT.split("\n")) {
  const m = line.match(/Missing 97-acceptance-criteria\.md in (\S+) \((\d+) topic/);
  if (m) folders.push({ folder: m[1], count: Number(m[2]) });
}

console.log(`Found ${folders.length} folders needing a stub.`);

let created = 0;
let skipped = 0;

for (const { folder, count } of folders) {
  const target = join(folder, "97-acceptance-criteria.md");
  if (existsSync(target)) {
    skipped += 1;
    continue;
  }

  const slug = basename(folder).toUpperCase().replace(/[^A-Z]/g, "");
  const idPrefix = `AT-${slug || "GEN"}`;

  const topics = readdirSync(folder)
    .filter(
      (f) =>
        /^\d{2}-.+\.md$/.test(f) &&
        !f.startsWith("97-") &&
        !f.startsWith("99-") &&
        f !== "00-overview.md"
    )
    .sort();

  const folderName = basename(folder).replace(/^\d+-/, "").replace(/-/g, " ");
  const titleCase = folderName.replace(/\b\w/g, (c) => c.toUpperCase());

  const rows = topics
    .map((f, i) => {
      const num = String(i + 1).padStart(2, "0");
      const range = `${idPrefix}-${num}`;
      return `| ${i + 1} | [\`${f}\`](./${f}) | ${range} | 📝 To populate |`;
    })
    .join("\n");

  const upRel = "../".repeat(folder.split("/").length - 1);

  const stub = `# ${titleCase} — Acceptance Criteria

> **Version:** 0.1.0
> **Created:** 2026-04-25 (UTC+8)
> **Status:** Scaffold — populate per-topic criteria during next refinement pass
> **Parent:** [\`00-overview.md\`](./00-overview.md)

---

## Purpose

Aggregated acceptance criteria for the ${count} topic file(s) in this folder. ID range: \`${idPrefix}-NN\`.

A criterion is *complete* when (a) it has a stable ID, (b) it references a source file, and (c) it is verifiable by reading the source or running an automated check.

---

## Coverage Map

| # | Source File | ID Range | Status |
|---|-------------|----------|--------|
${rows}

---

## Criteria

Per-topic criteria are tracked inline in each source file's \`## Acceptance Tests\` section (where present), or will be extracted here during the next refinement pass.

---

## Verification

\`\`\`bash
# List all referenced sources in this folder
grep -rn "${idPrefix}-" ${folder}/

# Run hygiene checks
node scripts/spec-hygiene/00-run-all.mjs
\`\`\`

---

## Related

- [\`00-overview.md\`](./00-overview.md) — Parent overview
- [\`spec/19-glossary.md\`](${upRel}19-glossary.md) — Terminology SSOT
- [\`spec/20-enums-index.md\`](${upRel}20-enums-index.md) — Enum registry

---

*Acceptance criteria scaffold v0.1.0 — auto-generated by \`scripts/spec-hygiene/13-generate-at-stubs.mjs\` (closes F-09).*
`;

  writeFileSync(target, stub);
  created += 1;
}

console.log(`✅ Created ${created} stub(s); skipped ${skipped} pre-existing file(s).`);
