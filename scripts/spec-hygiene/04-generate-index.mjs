#!/usr/bin/env node
/**
 * Spec Hygiene — Auto-Generate spec-index.md
 *
 * Walks spec/, extracts metadata from every .md file, and regenerates
 * spec/spec-index.md as a do-not-edit artefact.
 *
 * Closes AUD-D-01 (Critical, Drift): the previous hand-maintained index
 * went 9 days stale and listed 411 files vs. the actual 600+. This script
 * makes the index a build artefact so it can never drift.
 *
 * Extracts per file:
 *   - H1 title  (first `# ...` line, anywhere in the file)
 *   - Version   (first `Version:` field in the frontmatter or callout)
 *   - Status    (first `Status:` field, optional)
 *
 * Exit code 0 always (idempotent generator). To fail CI on drift, run
 * `git diff --exit-code spec/spec-index.md` after this script.
 */
import { readdirSync, readFileSync, writeFileSync, statSync } from "node:fs";
import { join, relative } from "node:path";

const ROOT = "spec";
const OUT = "spec/spec-index.md";

const TITLE_RE = /^#\s+(.+?)\s*$/m;
const VERSION_RE = /\*\*Version:\*\*\s*([0-9]+\.[0-9]+\.[0-9]+)/;
const STATUS_RE = /\*\*Status:\*\*\s*(\w+)/;

function collectFiles(dir) {
  const out = [];
  for (const name of readdirSync(dir)) {
    const full = join(dir, name);
    if (statSync(full).isDirectory()) {
      out.push(...collectFiles(full));
      continue;
    }
    if (full.endsWith(".md") === false) continue;
    out.push(full);
  }

  return out;
}

function extractMeta(file) {
  const text = readFileSync(file, "utf8");
  const titleMatch = TITLE_RE.exec(text);
  const versionMatch = VERSION_RE.exec(text);
  const statusMatch = STATUS_RE.exec(text);

  return {
    path: file,
    title: titleMatch ? titleMatch[1] : "(untitled)",
    version: versionMatch ? versionMatch[1] : "—",
    status: statusMatch ? statusMatch[1] : "—",
  };
}

function topLevelOf(file) {
  const rel = relative(ROOT, file);
  const seg = rel.split("/")[0];
  if (seg.endsWith(".md")) return "root";

  return seg;
}

function buildIndex() {
  const files = collectFiles(ROOT).sort();
  const meta = files.map(extractMeta);
  const groups = new Map();
  for (const m of meta) {
    const top = topLevelOf(m.path);
    if (groups.has(top) === false) groups.set(top, []);
    groups.get(top).push(m);
  }
  const today = new Date().toISOString().slice(0, 10);
  const lines = [];
  lines.push("# Spec File Index — Auto-Generated");
  lines.push("");
  lines.push("> **⚠️ DO NOT EDIT THIS FILE BY HAND**");
  lines.push("> ");
  lines.push("> This file is auto-generated by `scripts/spec-hygiene/04-generate-index.mjs`.");
  lines.push("> Any manual changes will be overwritten on the next run.");
  lines.push("");
  lines.push(`**Generated:** ${today}  `);
  lines.push(`**Total Files:** ${meta.length}  `);
  lines.push(`**Top-Level Folders:** ${groups.size}`);
  lines.push("");
  lines.push("> **How to search:** Use `Ctrl+F` / `Cmd+F` to search by keyword, file name, or title.");
  lines.push("");
  lines.push("---");
  lines.push("");
  lines.push("## Table of Contents");
  lines.push("");
  const sortedGroups = [...groups.entries()].sort(([a], [b]) => a.localeCompare(b));
  for (const [group, items] of sortedGroups) {
    const anchor = group.toLowerCase().replace(/[^a-z0-9]+/g, "-");
    lines.push(`- [${group}](#${anchor}) — ${items.length} file(s)`);
  }
  lines.push("");
  lines.push("---");
  lines.push("");
  for (const [group, items] of sortedGroups) {
    lines.push(`## ${group}`);
    lines.push("");
    lines.push("| File | Title | Version | Status |");
    lines.push("|------|-------|---------|--------|");
    const sortedItems = [...items].sort((a, b) => a.path.localeCompare(b.path));
    for (const item of sortedItems) {
      const rel = relative(ROOT, item.path);
      const safeTitle = item.title.replace(/\|/g, "\\|");
      lines.push(`| [\`${rel}\`](./${rel}) | ${safeTitle} | ${item.version} | ${item.status} |`);
    }
    lines.push("");
  }
  lines.push("---");
  lines.push("");
  lines.push(`*Auto-generated index — ${meta.length} files across ${groups.size} top-level folders.*`);
  writeFileSync(OUT, lines.join("\n") + "\n", "utf8");
  console.log(`✅ Wrote ${OUT} — ${meta.length} files across ${groups.size} folders`);
}

buildIndex();
