#!/usr/bin/env node
/**
 * Spec Hygiene — Auto-TOC Injector for `00-overview.md` files (L-3)
 *
 * Walks every folder in `spec/` that contains a `00-overview.md`. If the
 * folder has 2+ topic siblings (numeric-prefixed `.md` files other than
 * `00-overview.md` and the `97/98/99-` aggregates), inject an auto-TOC
 * block between sentinel comments:
 *
 *   <!-- AUTO-TOC:START -->
 *   ## Topics in this Folder
 *
 *   | # | File | Title | Lines |
 *   |---|------|-------|-------|
 *   | 1 | [`01-foo.md`](./01-foo.md) | Foo Title | 123 |
 *   ...
 *   <!-- AUTO-TOC:END -->
 *
 * Behaviour:
 *  - If sentinels exist → replace contents between them.
 *  - If sentinels missing → insert a new block right after the first H1
 *    (or right after the existing front-matter block, whichever is later).
 *  - Folders with <2 topic siblings are skipped (no useful TOC).
 *  - Folders whose overview already contains a manual `## Topics in this Folder`
 *    heading WITHOUT sentinels are skipped (treat as authored).
 *
 * Idempotent. Run via:  node scripts/spec-hygiene/11-generate-auto-toc.mjs
 *
 * Wired into `00-run-all.mjs`. Pair with `git diff --exit-code` in CI.
 */
import { readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";

const SPEC_ROOT = "spec";
const START = "<!-- AUTO-TOC:START -->";
const END = "<!-- AUTO-TOC:END -->";
const TITLE_RE = /^#\s+(.+?)\s*$/m;

function walk(dir) {
  const out = [];
  for (const name of readdirSync(dir)) {
    const p = join(dir, name);
    const s = statSync(p);
    if (s.isDirectory()) out.push(...walk(p));
    else out.push(p);
  }
  return out;
}

function topicSiblings(folder) {
  const entries = readdirSync(folder).filter((n) => /^\d{2}-/.test(n));
  const result = [];
  for (const name of entries) {
    if (/^(97|98|99)-/.test(name)) continue;
    if (name === "00-overview.md") continue;
    const full = join(folder, name);
    let isDir = false;
    try { isDir = statSync(full).isDirectory(); } catch { /* skip */ }
    if (isDir) {
      // Subfolder: include only if it has its own 00-overview.md
      try {
        statSync(join(full, "00-overview.md"));
        result.push({ name, isSubfolder: true });
      } catch { /* skip */ }
      continue;
    }
    if (name.endsWith(".md")) result.push({ name, isSubfolder: false });
  }
  return result.sort((a, b) => a.name.localeCompare(b.name));
}

function readTitle(file) {
  const txt = readFileSync(file, "utf8");
  const m = TITLE_RE.exec(txt);
  return m ? m[1].trim() : file.split("/").pop().replace(/\.md$/, "");
}

function lineCount(file) {
  return readFileSync(file, "utf8").split("\n").length;
}

function buildTocBlock(folder, siblings) {
  const lines = [
    START,
    "",
    "## Topics in this Folder",
    "",
    "*Auto-generated by `scripts/spec-hygiene/11-generate-auto-toc.mjs` — do not edit by hand inside the AUTO-TOC sentinels.*",
    "",
    "| # | File | Title | Lines |",
    "|---|------|-------|-------|",
  ];
  siblings.forEach((entry, idx) => {
    const { name, isSubfolder } = entry;
    if (isSubfolder) {
      const overviewPath = join(folder, name, "00-overview.md");
      const title = readTitle(overviewPath).replace(/\|/g, "\\|");
      lines.push(`| ${idx + 1} | [\`${name}/\`](./${name}/00-overview.md) | ${title} | subfolder |`);
      return;
    }
    const full = join(folder, name);
    const title = readTitle(full).replace(/\|/g, "\\|");
    const lc = lineCount(full);
    lines.push(`| ${idx + 1} | [\`${name}\`](./${name}) | ${title} | ${lc} |`);
  });
  lines.push("", END);
  return lines.join("\n");
}

function injectBlock(text, block) {
  // Replace existing block between sentinels.
  const startIdx = text.indexOf(START);
  const endIdx = text.indexOf(END);
  if (startIdx !== -1 && endIdx !== -1 && endIdx > startIdx) {
    const before = text.slice(0, startIdx);
    const after = text.slice(endIdx + END.length);
    return `${before}${block}${after}`;
  }
  // Insert after the H1 + a blank line. Fall back to appending.
  const h1Match = text.match(/^#\s+.+\n/m);
  if (h1Match) {
    const insertAt = (h1Match.index ?? 0) + h1Match[0].length;
    // Skip an existing meta block (lines starting with > or **) right after H1
    let cursor = insertAt;
    const lines = text.slice(insertAt).split("\n");
    let consumed = 0;
    for (const line of lines) {
      if (line.startsWith(">") || line.startsWith("**") || line.trim() === "") {
        consumed += line.length + 1;
        continue;
      }
      break;
    }
    cursor = insertAt + consumed;
    return `${text.slice(0, cursor)}\n${block}\n\n${text.slice(cursor)}`;
  }
  return `${text.replace(/\s+$/g, "")}\n\n${block}\n`;
}

const overviews = walk(SPEC_ROOT).filter((f) => f.endsWith("/00-overview.md"));
let updated = 0;
let skipped = 0;
let insertedNew = 0;

for (const overview of overviews) {
  const folder = dirname(overview);
  const siblings = topicSiblings(folder);
  if (siblings.length < 2) {
    skipped += 1;
    continue;
  }
  const txt = readFileSync(overview, "utf8");
  const hasSentinels = txt.includes(START) && txt.includes(END);
  const hasManualHeading =
    !hasSentinels && /^##\s+Topics in this Folder\b/m.test(txt);
  if (hasManualHeading) {
    skipped += 1;
    continue;
  }
  const block = buildTocBlock(folder, siblings);
  const next = injectBlock(txt, block);
  if (next === txt) {
    skipped += 1;
    continue;
  }
  writeFileSync(overview, next, "utf8");
  updated += 1;
  if (!hasSentinels) insertedNew += 1;
}

console.log(
  `✅ Auto-TOC: updated ${updated} (${insertedNew} newly inserted), skipped ${skipped}`,
);
