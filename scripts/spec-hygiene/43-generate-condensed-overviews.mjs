#!/usr/bin/env node
// P11 — Generate 00-overview-condensed.md for mega-sections.
// Strategy: stitch together (a) the 00-overview.md AI Contract, (b) one-line summaries
// of every subdir (first H1 + first non-blank prose line), (c) the full
// 97-acceptance-criteria.md table, (d) the section's contract.json slice.
// Cap output at 17 KB so it fits comfortably under the audit runner's 18 KB input cap.

import fs from 'node:fs';
import path from 'node:path';

const SECTIONS = [
  '02-coding-guidelines',
  '15-wp-plugin-how-to',
  '03-error-manage',
  '31-app',
  '32-ui-design',
];
const CAP = 17000;
const SPEC = 'spec';

const contract = JSON.parse(fs.readFileSync(path.join(SPEC, 'contract.json'), 'utf8'));

function firstHeadingAndLead(file) {
  const txt = fs.readFileSync(file, 'utf8').split('\n');
  let h = '', lead = '';
  for (const line of txt) {
    if (!h && /^#\s+/.test(line)) { h = line.replace(/^#\s+/, '').trim(); continue; }
    if (h && !lead && line.trim() && !line.startsWith('>') && !line.startsWith('#') && !line.startsWith('---')) {
      lead = line.trim().slice(0, 200);
      break;
    }
  }
  return { h, lead };
}

function summariseSubdirs(sectionDir) {
  const entries = fs.readdirSync(sectionDir, { withFileTypes: true });
  const out = [];
  for (const e of entries.sort((a, b) => a.name.localeCompare(b.name))) {
    const p = path.join(sectionDir, e.name);
    if (e.isDirectory()) {
      // pick the subdir's 00-overview.md if present, else first .md
      const sub = fs.readdirSync(p).filter(n => n.endsWith('.md')).sort();
      const target = sub.find(n => /^00-overview/.test(n)) || sub[0];
      if (!target) continue;
      const { h, lead } = firstHeadingAndLead(path.join(p, target));
      out.push(`- **\`${e.name}/\`** — ${h || '(no heading)'}${lead ? ' · ' + lead : ''}`);
    } else if (e.name.endsWith('.md') && !/^00-overview|^9[0-9]|consistency|changelog/i.test(e.name)) {
      const { h, lead } = firstHeadingAndLead(p);
      out.push(`- **\`${e.name}\`** — ${h || '(no heading)'}${lead ? ' · ' + lead : ''}`);
    }
  }
  return out.join('\n');
}

function loadIfExists(p) { try { return fs.readFileSync(p, 'utf8'); } catch { return ''; } }

function buildCondensed(section) {
  const dir = path.join(SPEC, section);
  const overview = loadIfExists(path.join(dir, '00-overview.md'));
  const acceptance = loadIfExists(path.join(dir, '97-acceptance-criteria.md'));
  const inventory = summariseSubdirs(dir);

  // contract slice: ATs whose prefix matches this section's typical id space
  const sectionAts = (contract.acceptance_tests || []).filter(at => (at.file || '').includes(`/${section}/`));
  const sectionEps = (contract.endpoints || []).filter(ep => (ep.file || '').includes(`/${section}/`));
  const atSummary = sectionAts.length
    ? `**Acceptance tests defined in this section:** ${sectionAts.length}\n` +
      'Examples: ' + sectionAts.slice(0, 12).map(a => '`' + a.id + '`').join(', ') +
      (sectionAts.length > 12 ? ` … +${sectionAts.length - 12} more` : '')
    : '_No ATs defined directly in this section._';
  const epSummary = sectionEps.length
    ? `**Endpoints defined in this section:** ${sectionEps.length}\n` +
      'Examples: ' + sectionEps.slice(0, 8).map(e => '`' + e.id + ' ' + (e.method || '') + ' ' + (e.path || '') + '`').join(', ')
    : '_No endpoints defined directly in this section._';

  let body = '';
  body += `# Condensed Overview — \`spec/${section}/\` (P11)\n\n`;
  body += `> **Audit-runner input.** Auto-generated by [\`scripts/spec-hygiene/43-generate-condensed-overviews.mjs\`](../../scripts/spec-hygiene/43-generate-condensed-overviews.mjs).\n`;
  body += `> The full section is too large to fit the AI auditor's 18 KB context cap, so this file is the canonical AI-input summary. **Do not edit by hand.**\n`;
  body += `> Source-of-truth files remain in this same folder.\n\n`;

  body += `## 1. AI Contract (verbatim from \`00-overview.md\`)\n\n`;
  // extract just the AI Contract block from the overview
  const aiBlockMatch = overview.match(/## AI Contract[\s\S]*?(?=\n## |\n# |$)/);
  body += (aiBlockMatch ? aiBlockMatch[0] : overview.slice(0, 2000)) + '\n\n';

  body += `## 2. Section inventory (one-line summary per file/folder)\n\n`;
  body += inventory + '\n\n';

  body += `## 3. Contract.json slice\n\n`;
  body += atSummary + '\n\n' + epSummary + '\n\n';

  body += `## 4. Acceptance criteria (verbatim from \`97-acceptance-criteria.md\`)\n\n`;
  body += acceptance + '\n';

  // truncate to CAP, but keep AC table if possible
  if (body.length > CAP) {
    body = body.slice(0, CAP) + '\n\n_… truncated at ' + CAP + ' chars to fit AI auditor cap …_\n';
  }
  return body;
}

let written = 0;
for (const s of SECTIONS) {
  const content = buildCondensed(s);
  const out = path.join(SPEC, s, '00-overview-condensed.md');
  fs.writeFileSync(out, content);
  console.log(`✓ ${out}  ${content.length} chars`);
  written++;
}
console.log(`\nWrote ${written} condensed overviews.`);
